//! One function per toolkit. Each returns (path relative to --out, contents).

use nordlys_config::{Palette, Rgb};
use std::fmt::Write;

pub fn all(p: &Palette) -> Vec<(&'static str, String)> {
    let gtk = gtk_css(p);
    vec![
        ("gtk-4.0/gtk.css", gtk.clone()),
        ("gtk-3.0/gtk.css", gtk),
        ("qt6ct/colors/nordlys.conf", qt_scheme(p)),
        ("foot/nordlys.ini", foot(p)),
    ]
}

/// libadwaita and GTK 3 both honour these named colours.
fn gtk_css(p: &Palette) -> String {
    let pairs: [(&str, Rgb); 14] = [
        ("accent_color", p.accent),
        ("accent_bg_color", p.accent),
        ("accent_fg_color", p.on_accent),
        ("window_bg_color", p.ground),
        ("window_fg_color", p.text),
        ("view_bg_color", p.surface),
        ("view_fg_color", p.text),
        ("headerbar_bg_color", p.surface),
        ("headerbar_fg_color", p.text),
        ("card_bg_color", p.raised),
        ("card_fg_color", p.text),
        ("popover_bg_color", p.raised),
        ("popover_fg_color", p.text),
        ("sidebar_bg_color", p.surface),
    ];
    let mut s = String::from("/* Generated by nordlys-theme. Edit nordlys.toml instead. */\n");
    for (name, c) in pairs {
        let _ = writeln!(s, "@define-color {name} {};", c.hex());
    }
    s
}

/// qt6ct colour scheme. The 21 entries follow QPalette::ColorRole order.
fn qt_scheme(p: &Palette) -> String {
    let roles = [
        p.text,      // WindowText
        p.raised,    // Button
        p.border,    // Light
        p.raised,    // Midlight
        p.ground,    // Dark
        p.border,    // Mid
        p.text,      // Text
        p.text,      // BrightText
        p.text,      // ButtonText
        p.surface,   // Base
        p.ground,    // Window
        p.ground,    // Shadow
        p.accent,    // Highlight
        p.on_accent, // HighlightedText
        p.accent,    // Link
        p.ansi[5],   // LinkVisited
        p.raised,    // AlternateBase
        p.ground,    // NoRole
        p.raised,    // ToolTipBase
        p.text,      // ToolTipText
        p.dim,       // PlaceholderText
    ];
    let row = |dim: bool| {
        roles
            .iter()
            .map(|c| {
                let c = if dim { mix(*c, p.ground, 0.45) } else { *c };
                format!("#ff{}", c.bare().to_lowercase())
            })
            .collect::<Vec<_>>()
            .join(", ")
    };
    format!(
        "[ColorScheme]\nactive_colors={}\ndisabled_colors={}\ninactive_colors={}\n",
        row(false),
        row(true),
        row(false)
    )
}

/// Include from foot.ini with `include=~/.config/foot/nordlys.ini`.
fn foot(p: &Palette) -> String {
    let mut s = String::from("# Generated by nordlys-theme.\n[colors]\n");
    let _ = writeln!(s, "background={}", p.ground.bare());
    let _ = writeln!(s, "foreground={}", p.text.bare());
    let _ = writeln!(
        s,
        "selection-background={}",
        mix(p.accent, p.ground, 0.65).bare()
    );
    let _ = writeln!(s, "selection-foreground={}", p.text.bare());
    let _ = writeln!(s, "alpha=0.86");
    for (i, c) in p.ansi.iter().enumerate() {
        let key = if i < 8 {
            format!("regular{i}")
        } else {
            format!("bright{}", i - 8)
        };
        let _ = writeln!(s, "{key}={}", c.bare());
    }
    s
}

/// Blend `a` toward `b` by `t` (0.0 = a, 1.0 = b).
fn mix(a: Rgb, b: Rgb, t: f32) -> Rgb {
    let m = |x: u8, y: u8| (x as f32 + (y as f32 - x as f32) * t).round() as u8;
    Rgb(m(a.0, b.0), m(a.1, b.1), m(a.2, b.2))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn qt_scheme_has_21_roles_per_row() {
        let s = qt_scheme(&Palette::dark());
        for line in s.lines().skip(1) {
            let (_, v) = line.split_once('=').unwrap();
            assert_eq!(v.split(", ").count(), 21, "{line}");
        }
    }

    #[test]
    fn gtk_uses_the_accent() {
        let css = gtk_css(&Palette::light());
        assert!(css.contains("@define-color accent_bg_color #2F5BD8;"));
    }

    #[test]
    fn foot_lists_all_16_colours() {
        let f = foot(&Palette::dark());
        assert!(f.contains("regular0=") && f.contains("bright7="));
    }
}
